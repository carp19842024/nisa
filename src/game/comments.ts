/** ドローダウンからコメントの段階（-1 は出さない）を決める */
export function commentTier(drawdown: number, tiers: readonly number[]): number {
  let tier = -1;
  tiers.forEach((th, i) => {
    if (drawdown >= th) tier = i;
  });
  return tier;
}

